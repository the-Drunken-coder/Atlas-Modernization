import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(packageRoot, "../protocol/schema/jsonschema/atlas.schema.json");
const revisionPath = join(packageRoot, "../protocol/generated/revision.txt");
const outputPath = join(packageRoot, "src/generated/radio-contract.generated.ts");

const operations = [
  ["entity.get", "request", undefined, "EntityResource"],
  ["entity.create", "mutation", "EntityCreateRequest", "EntityResource"],
  ["entity.update", "mutation", "EntityUpdateRequest", "EntityResource"],
  ["entity.delete", "mutation", undefined, undefined],
  ["entity.check_in", "mutation", "EntityCheckInRequest", "EntityCheckInResponse"],
  ["task.get", "request", undefined, "TaskResource"],
  ["task.create", "mutation", "TaskCreateRequest", "TaskResource"],
  ["task.acknowledge", "mutation", "TaskAcknowledgeRequest", "TaskResource"],
  ["task.start", "mutation", "TaskStartRequest", "TaskResource"],
  ["task.progress", "mutation", "TaskProgressRequest", "TaskResource"],
  ["task.complete", "mutation", "TaskCompleteRequest", "TaskResource"],
  ["task.fail", "mutation", "TaskFailRequest", "TaskResource"],
  ["task.cancel", "mutation", "TaskCancelRequest", "TaskResource"],
  ["runtime.begin", "mutation", "RuntimeRegistrationRequest", undefined],
  ["runtime.stop", "mutation", "RuntimeStopRequest", undefined],
  ["runtime.ready", "mutation", "RuntimeReadyRequest", undefined],
  ["runtime.tasks", "request", undefined, "RuntimeTaskDeliveryResponse"],
  ["object.get", "request", undefined, "ObjectDetailResource"],
  ["object.create", "mutation", "ObjectCreateRequest", "ObjectDetailResource"],
  ["object.update", "mutation", "ObjectUpdateRequest", "ObjectDetailResource"],
  ["object.delete", "mutation", undefined, undefined],
  ["object.content", "request", undefined, undefined],
  ["query.full", "request", undefined, "FullDatasetResponse"],
  ["query.changed_since", "request", undefined, "ChangedSinceResponse"],
  ["command_catalog.get", "request", undefined, "CommandCatalog"],
  ["plugin.list", "request", undefined, "PluginDiscoveryResponse"],
  ["plugin.invoke", "request", "JSONValue", "JSONValue"],
  ["plugin.invoke_spatial", "request", "MapArea", "SpatialOperationResult"]
];

const schemaText = await readFile(schemaPath, "utf8");
const schema = JSON.parse(schemaText);
const definitions = Object.keys(schema.$defs ?? {}).sort();
const definitionSet = new Set(definitions);
for (const [, , input, output] of operations) {
  for (const definition of [input, output]) {
    if (definition !== undefined && !definitionSet.has(definition)) {
      throw new Error(`Atlas Protocol schema is missing ${definition}`);
    }
  }
}

const revision = (await readFile(revisionPath, "utf8")).trim();
const schemaDigest = `sha256:${createHash("sha256")
  .update("schema/jsonschema/atlas.schema.json")
  .update("\0")
  .update(schemaText)
  .update("\0")
  .digest("hex")}`;
if (revision !== schemaDigest) {
  throw new Error(`Atlas Protocol revision ${revision} does not match schema ${schemaDigest}`);
}

const operationEntries = Object.fromEntries(
  operations.map(([name, kind, input, output]) => [
    name,
    { kind, ...(input === undefined ? {} : { input }), ...(output === undefined ? {} : { output }) }
  ])
);
const radioRevision = `sha256:${createHash("sha256")
  .update("atlas-meshtastic-link-radio-contract-v1")
  .update("\0")
  .update(revision)
  .update("\0")
  .update(JSON.stringify(operationEntries))
  .digest("hex")}`;
const importedTypes = [...new Set(operations.flatMap(([, , input, output]) => [input, output]).filter(Boolean))].sort();
const inputMap = operations.map(([name, , input]) => `  ${JSON.stringify(name)}: ${input ?? "undefined"};`).join("\n");
const outputMap = operations
  .map(([name, , , output]) => `  ${JSON.stringify(name)}: ${output ?? "undefined"};`)
  .join("\n");

const generated = `// Code generated by scripts/generate-contract.mjs; DO NOT EDIT.\n\nimport type {\n${importedTypes.map((name) => `  ${name}`).join(",\n")}\n} from "@the-drunken-coder/atlas-sdk";\n\nexport const ATLAS_PROTOCOL_REVISION = ${JSON.stringify(revision)} as const;\nexport const RADIO_CONTRACT_REVISION = ${JSON.stringify(radioRevision)} as const;\n\nexport const ATLAS_PROTOCOL_DEFINITIONS = ${JSON.stringify(definitions, null, 2)} as const;\n\nexport const ATLAS_RADIO_OPERATIONS = ${JSON.stringify(operationEntries, null, 2)} as const;\n\nexport type AtlasProtocolDefinitionName = (typeof ATLAS_PROTOCOL_DEFINITIONS)[number];\nexport type AtlasRadioOperationName = keyof typeof ATLAS_RADIO_OPERATIONS;\nexport type AtlasRadioRequestOperation = {\n  [Operation in AtlasRadioOperationName]: (typeof ATLAS_RADIO_OPERATIONS)[Operation]["kind"] extends "request" ? Operation : never;\n}[AtlasRadioOperationName];\nexport type AtlasRadioMutationOperation = Exclude<AtlasRadioOperationName, AtlasRadioRequestOperation>;\nexport type AtlasRadioInputByOperation = {\n${inputMap}\n};\nexport type AtlasRadioOutputByOperation = {\n${outputMap}\n};\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "generated Radio contract is stale; run npm run generate --workspace @the-drunken-coder/atlas-meshtastic-link"
    );
  }
} else {
  await writeFile(outputPath, generated);
}
