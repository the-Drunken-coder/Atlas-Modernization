import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const packageJSON = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));
const packageVersion = process.env.ATLAS_CORE_PACKAGE_VERSION ?? packageJSON.version;
const packageImage = process.env.ATLAS_CORE_PACKAGE_IMAGE ?? packageJSON.atlasCoreImage;
const protocolRevisionPath = join(
  packageRoot,
  "..",
  "..",
  "packages",
  "protocol",
  "generated",
  "typescript",
  "revision.ts"
);
const protocolRevisionSource = readFileSync(protocolRevisionPath, "utf8");
const protocolRevision = protocolRevisionSource.match(
  /ATLAS_PROTOCOL_REVISION\s*=\s*["'](sha256:[0-9a-f]{64})["']/u
)?.[1];

if (typeof packageJSON.name !== "string" || typeof packageVersion !== "string") {
  throw new Error("package.json must contain string name and version fields");
}
if (
  packageImage !== null &&
  (typeof packageImage !== "string" ||
    !/^ghcr\.io\/the-drunken-coder\/atlas-core@sha256:[0-9a-f]{64}$/.test(packageImage))
) {
  throw new Error("package.json atlasCoreImage must be null or an immutable Atlas Core GHCR digest reference");
}
if (!protocolRevision) throw new Error("generated Atlas Protocol revision is missing or malformed");

writeFileSync(
  join(packageRoot, "src/package-metadata.ts"),
  `// Generated by scripts/generate-package-metadata.mjs. Do not edit.\nexport const PACKAGE_NAME = ${JSON.stringify(packageJSON.name)};\nexport const PACKAGE_VERSION = ${JSON.stringify(packageVersion)};\nexport const PACKAGE_IMAGE: string | undefined = ${packageImage === null ? "undefined" : JSON.stringify(packageImage)};\nexport const PACKAGE_PLUGIN_CONTRACTS = {\n  coreToPluginProtocolMajors: [1],\n  pluginToSourceGatewayProtocolMajors: [1],\n  atlasProtocolRevision: ${JSON.stringify(protocolRevision)},\n  supportedPackageSchemaMajors: [1],\n  supportedInteractions: ["map_area"]\n} as const;\n`
);
