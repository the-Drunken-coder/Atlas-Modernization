import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const packageJSON = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));

if (typeof packageJSON.name !== "string" || typeof packageJSON.version !== "string") {
  throw new Error("package.json must contain string name and version fields");
}
if (
  packageJSON.atlasCoreImage !== null &&
  (typeof packageJSON.atlasCoreImage !== "string" ||
    !/^ghcr\.io\/the-drunken-coder\/atlas-core@sha256:[0-9a-f]{64}$/.test(packageJSON.atlasCoreImage))
) {
  throw new Error("package.json atlasCoreImage must be null or an immutable Atlas Core GHCR digest reference");
}

writeFileSync(
  join(packageRoot, "src/package-metadata.ts"),
  `// Generated by scripts/generate-package-metadata.mjs. Do not edit.\nexport const PACKAGE_NAME = ${JSON.stringify(packageJSON.name)};\nexport const PACKAGE_VERSION = ${JSON.stringify(packageJSON.version)};\nexport const PACKAGE_IMAGE: string | undefined = ${packageJSON.atlasCoreImage === null ? "undefined" : JSON.stringify(packageJSON.atlasCoreImage)};\n`
);
