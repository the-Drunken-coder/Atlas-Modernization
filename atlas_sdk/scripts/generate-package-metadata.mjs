import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(scriptDir, "..");
const packageJSON = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8"));

if (typeof packageJSON.name !== "string" || packageJSON.name.trim() === "") {
  throw new Error("package.json name must be a non-empty string");
}
if (typeof packageJSON.bin?.atlas !== "string" || packageJSON.bin.atlas.trim() === "") {
  throw new Error("package.json bin.atlas must be a non-empty string");
}

const source = `// Code generated by scripts/generate-package-metadata.mjs; DO NOT EDIT.

export const PACKAGE_NAME = ${JSON.stringify(packageJSON.name)} as const;
export const PACKAGE_BIN = ${JSON.stringify(packageJSON.bin)} as const;
`;

writeFileSync(join(packageRoot, "src/package-metadata.ts"), source);
